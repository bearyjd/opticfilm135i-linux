#!/bin/sh
# Regenerate tests/golden/gl126_load_film_*transfers.txt, the transfer
# sequences tests/test_sane_magazine.py compares the GL126 "Load film"
# flow against, from a build WITHOUT the load's failure diagnostics:
#
#   sane-backends 18bea9b32 (the SANE v9 tip the diagnostics apply to)
#   + ONLY the test hooks, test_usb_device.{h,cpp} and
#     test_scanner_interface.{h,cpp}, taken from <commit>
#   with gl126.cpp, gl126_ops.cpp and gl126_ops.h left at 18bea9b32
#   (checked below, the script stops otherwise).
#
# Usage:
#   tests/gen_gl126_load_film_goldens.sh <sane-backends repo> <commit> <scratch dir>
#
# <commit> is the commit carrying the test hooks (the diagnostics commit
# itself: only its four test files are used). <scratch dir> must not
# exist; a detached git worktree of <sane-backends repo> is created there
# and built (autogen, configure --sysconfdir=/etc, lib, sanei,
# backend/libsane-genesys.la). It is left in place afterwards; remove it
# with `git -C <sane-backends repo> worktree remove --force <scratch dir>`.
#
# Each golden starts with "#" lines naming the base and the blob hashes of
# the files built, which the tests skip. Rerunning on the same inputs
# writes byte-identical files, so `git diff tests/golden` after a rerun
# is the provenance check.

set -eu

BASE=18bea9b32
HOOKS="backend/genesys/test_usb_device.h backend/genesys/test_usb_device.cpp
backend/genesys/test_scanner_interface.h backend/genesys/test_scanner_interface.cpp"
UNCHANGED="backend/genesys/gl126.cpp backend/genesys/gl126_ops.cpp backend/genesys/gl126_ops.h"

if [ $# -ne 3 ]; then
    echo "usage: $0 <sane-backends repo> <commit> <scratch dir>" >&2
    exit 2
fi
SB_REPO=$1
COMMIT=$2
WORK=$3
TESTS_DIR=$(cd "$(dirname "$0")" && pwd)

if [ -e "$WORK" ]; then
    echo "$WORK exists; give a new directory" >&2
    exit 2
fi

git -C "$SB_REPO" worktree add --detach "$WORK" "$BASE"
# shellcheck disable=SC2086
git -C "$WORK" checkout "$COMMIT" -- $HOOKS

# Only the hooks may differ from the base.
changed=$(git -C "$WORK" diff --cached --name-only "$BASE" | sort)
want=$(printf '%s\n' $HOOKS | sort)
others=$(printf '%s\n' "$changed" | grep -vxF "$want" || true)
if [ -n "$others" ]; then
    echo "files other than the test hooks differ from $BASE:" >&2
    echo "$others" >&2
    exit 1
fi
# shellcheck disable=SC2086
if ! git -C "$WORK" diff --quiet "$BASE" -- $UNCHANGED; then
    echo "gl126.cpp or gl126_ops.* differ from $BASE" >&2
    exit 1
fi

(
    cd "$WORK"
    ./autogen.sh
    ./configure --sysconfdir=/etc
    make -C lib
    make -C sanei
    make -C backend libsane-genesys.la
) > "$WORK/gen-goldens-build.log" 2>&1 || {
    echo "build failed, see $WORK/gen-goldens-build.log" >&2
    exit 1
}

provenance="generated by tests/gen_gl126_load_film_goldens.sh
base: sane-backends $(git -C "$WORK" rev-parse "$BASE")"
for f in $HOOKS $UNCHANGED; do
    provenance="$provenance
$(git -C "$WORK" hash-object "$f") $f"
done

SANE_BACKENDS_DIR=$WORK python3 "$TESTS_DIR/test_sane_magazine.py" \
    --write-load-goldens "$provenance"
